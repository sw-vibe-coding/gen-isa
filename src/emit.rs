fn emit_format_encoder(out: &mut String, f: &Format, spec: &Spec) {
    let total_bits = (f.size_bytes * 8) as u32;
    let int_ty = uint_type_for_bits(total_bits);
    let endian_method = match spec.memory.endian {
        Endian::Big => "to_be_bytes",
        Endian::Little => "to_le_bytes",
    };
    let fields = encodable_fields(f);
    let args: String = fields
        .iter()
        .map(|fld| format!("{}: {}", fld.name, field_type(fld)))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(
        out,
        "fn encode_{name}({args}, out: &mut [u8]) -> Result<usize, EncodeError> {{\n\
         \x20   if out.len() < {bytes} {{ return Err(EncodeError::BufferTooSmall); }}\n\
         \x20   let mut word: {int_ty} = 0;",
        name = f.name,
        bytes = f.size_bytes,
    );
    for fld in &f.fields {
        let shift = total_bits - fld.offset - fld.width;
        let mask = if fld.width == 64 {
            u64::MAX
        } else {
            (1u64 << fld.width) - 1
        };
        match fld.kind {
            FieldKind::Reserved => {
                let value = fld.value.unwrap_or(0);
                let _ = writeln!(
                    out,
                    "    word |= ({value}{int_ty} & 0x{mask:X}) << {shift};",
                );
            }
            FieldKind::Indirect => {
                let _ = writeln!(
                    out,
                    "    word |= (({} as {int_ty}) & 0x{mask:X}) << {shift};",
                    fld.name
                );
            }
            FieldKind::Disp => {
                if fld.signed {
                    let cast_to = uint_type_for_bits(fld.width);
                    let _ = writeln!(
                        out,
                        "    word |= (({} as {cast_to} as {int_ty}) & 0x{mask:X}) << {shift};",
                        fld.name
                    );
                } else {
                    let _ = writeln!(
                        out,
                        "    word |= (({} as {int_ty}) & 0x{mask:X}) << {shift};",
                        fld.name
                    );
                }
            }
            FieldKind::Imm | FieldKind::Tag | FieldKind::Reg | FieldKind::Opcode => {
                let _ = writeln!(
                    out,
                    "    word |= (({} as {int_ty}) & 0x{mask:X}) << {shift};",
                    fld.name
                );
            }
        }
    }
    let _ = writeln!(
        out,
        "    out[..{bytes}].copy_from_slice(&word.{endian_method}());\n\
         \x20   Ok({bytes})\n\
         }}\n",
        bytes = f.size_bytes,
    );
}

/// Generated `src/decode.rs`.
pub fn decode_rs(spec: &Spec) -> String {
    if spec.encoding.style == EncodingStyle::RomTable {
        return rom_table_decode_stub();
    }
    let mut out = String::new();
    out.push_str("//! Decoding helpers.\n");
    out.push_str("//!\n");
    out.push_str("//! Generated by gen-isa from the ISA spec.\n\n");
    out.push_str("use crate::{Instruction, opcode::Opcode};\n");
    out.push_str("use sw_isa_core::DecodeError;\n\n");

    out.push_str("pub fn decode(bytes: &[u8]) -> Result<(Instruction, usize), DecodeError> {\n");

    if spec.encoding.length_dispatch == LengthDispatch::FirstWordBits {
        emit_first_word_dispatch(&mut out, spec);
    } else {
        emit_per_opcode_dispatch(&mut out, spec);
    }

    out.push_str("}\n\n");

    for f in &spec.formats {
        emit_format_decoder(&mut out, f, spec);
    }
    out
}

