//! Spec-driven code generation: turn a [`crate::spec::Spec`] into the
//! mechanical Rust files of a `sw-{slug}-isa` crate.
//!
//! Step 5 (`scaffolder-codegen`). For `encoding_style = "bit_fields"`, emits
//! working `encode.rs` / `decode.rs` / `lib.rs` with `Architecture` impl.
//! For `encoding_style = "rom_table"` (COR24), emits opcode/register/branch
//! tables but stubs encode/decode (those are hand-supplied per
//! `gen-isa/docs/decisions.md` Sec 14).

use crate::spec::{
    EncodingStyle, Endian, Field, FieldKind, Format, LengthDispatch, RegClass, Spec,
};
use std::fmt::Write as _;

/// Generated `src/opcode.rs`.
pub fn opcode_rs(spec: &Spec) -> String {
    let mut out = String::new();
    out.push_str("//! Opcode enum and metadata.\n");
    out.push_str("//!\n");
    out.push_str("//! Generated by gen-isa from the ISA spec; do not edit by hand.\n");
    out.push_str("//! Re-run the scaffolder to regenerate.\n\n");

    out.push_str("#[derive(Copy, Clone, Debug, Eq, PartialEq)]\n");
    out.push_str("#[repr(u8)]\n");
    out.push_str("pub enum Opcode {\n");
    for op in &spec.opcodes {
        let _ = writeln!(out, "    {} = 0x{:02X},", op.name, op.value);
    }
    out.push_str("}\n\n");

    out.push_str("impl Opcode {\n");

    // mnemonic()
    out.push_str("    pub fn mnemonic(self) -> &'static str {\n");
    out.push_str("        match self {\n");
    for op in &spec.opcodes {
        let _ = writeln!(
            out,
            "            Opcode::{} => \"{}\",",
            op.name, op.mnemonic
        );
    }
    out.push_str("        }\n");
    out.push_str("    }\n\n");

    // formats()
    out.push_str("    pub fn formats(self) -> &'static [&'static str] {\n");
    out.push_str("        match self {\n");
    for op in &spec.opcodes {
        let names = op.format_names();
        let arr = names
            .iter()
            .map(|n| format!("\"{n}\""))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "            Opcode::{} => &[{arr}],", op.name);
    }
    out.push_str("        }\n");
    out.push_str("    }\n\n");

    // try_from_value(): byte -> first matching opcode (note: ambiguous if
    // values repeat across formats; spec validation does not forbid that
    // globally, so we use first-declared-wins).
    out.push_str("    pub fn try_from_value(v: u8) -> Option<Self> {\n");
    out.push_str("        match v {\n");
    let mut seen_values = std::collections::BTreeSet::new();
    for op in &spec.opcodes {
        if seen_values.insert(op.value) {
            let _ = writeln!(
                out,
                "            0x{:02X} => Some(Opcode::{}),",
                op.value, op.name
            );
        }
    }
    out.push_str("            _ => None,\n");
    out.push_str("        }\n");
    out.push_str("    }\n");

    out.push_str("}\n\n");

    // Mnemonic trait impl
    out.push_str("impl sw_isa_core::Mnemonic for Opcode {\n");
    out.push_str("    fn mnemonic(&self) -> &'static str {\n");
    out.push_str("        Opcode::mnemonic(*self)\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    out
}

/// Generated `src/register.rs`.
pub fn register_rs(spec: &Spec) -> String {
    let mut out = String::new();
    out.push_str("//! Register definitions.\n");
    out.push_str("//!\n");
    out.push_str("//! Generated by gen-isa from the ISA spec; do not edit by hand.\n\n");

    out.push_str("#[derive(Copy, Clone, Debug, Eq, PartialEq)]\n");
    out.push_str("pub enum Reg {\n");
    for r in &spec.registers {
        let _ = writeln!(out, "    {},", pascal(&r.name));
    }
    out.push_str("}\n\n");

    out.push_str("#[derive(Copy, Clone, Debug, Eq, PartialEq)]\n");
    out.push_str("pub enum RegClass {\n");
    out.push_str("    Gpr, Acc, Ext, Xr, Reserved, Pc, Sp, Fp, Flags,\n");
    out.push_str("}\n\n");

    out.push_str("impl Reg {\n");
    out.push_str("    pub fn name(self) -> &'static str {\n");
    out.push_str("        match self {\n");
    for r in &spec.registers {
        let _ = writeln!(
            out,
            "            Reg::{} => \"{}\",",
            pascal(&r.name),
            r.name
        );
    }
    out.push_str("        }\n");
    out.push_str("    }\n\n");

    out.push_str("    pub fn class(self) -> RegClass {\n");
    out.push_str("        match self {\n");
    for r in &spec.registers {
        let _ = writeln!(
            out,
            "            Reg::{} => RegClass::{},",
            pascal(&r.name),
            class_variant(r.class)
        );
    }
    out.push_str("        }\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");

    out.push_str("impl sw_isa_core::register::RegisterId for Reg {\n");
    out.push_str("    fn index(self) -> u32 {\n");
    out.push_str("        match self {\n");
    for r in &spec.registers {
        let _ = writeln!(out, "            Reg::{} => {},", pascal(&r.name), r.index);
    }
    out.push_str("        }\n");
    out.push_str("    }\n\n");
    out.push_str("    fn name(self) -> &'static str {\n");
    out.push_str("        Reg::name(self)\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");

    out.push_str("pub fn parse_register(s: &str) -> Option<Reg> {\n");
    out.push_str("    match s {\n");
    for r in &spec.registers {
        let _ = writeln!(
            out,
            "        \"{}\" => Some(Reg::{}),",
            r.name,
            pascal(&r.name)
        );
    }
    out.push_str("        _ => None,\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    out
}

/// Generated `src/branch.rs`.
pub fn branch_rs(spec: &Spec) -> String {
    let max_bytes = spec.memory.max_instr_bytes;
    format!(
        "//! Branch range constants.\n\
         //!\n\
         //! Generated by gen-isa from the ISA spec; do not edit by hand.\n\
         \n\
         pub const BRANCH_OFFSET_MIN: i32 = {};\n\
         pub const BRANCH_OFFSET_MAX: i32 = {};\n\
         pub const MAX_INSTRUCTION_BYTES: usize = {max_bytes};\n\
         pub const MAX_SHORT_BRANCH_INSTRUCTIONS: usize = {};\n\
         pub const PIPELINE_DELAY_BYTES: u32 = {};\n\
         \n\
         pub fn can_short_branch(from: usize, to: usize) -> bool {{\n\
         \x20   from.abs_diff(to) <= MAX_SHORT_BRANCH_INSTRUCTIONS\n\
         }}\n",
        spec.branch.short_offset_min,
        spec.branch.short_offset_max,
        spec.branch.max_short_branch_instructions,
        spec.branch.pipeline_delay_bytes,
    )
}

/// Generated `src/encode.rs`.
pub fn encode_rs(spec: &Spec) -> String {
    if spec.encoding.style == EncodingStyle::RomTable {
        return rom_table_encode_stub();
    }
    let mut out = String::new();
    out.push_str("//! Encoding helpers.\n");
    out.push_str("//!\n");
    out.push_str("//! Generated by gen-isa from the ISA spec.\n\n");
    out.push_str("use crate::Instruction;\n");
    out.push_str("use crate::opcode::Opcode;\n");
    out.push_str("use sw_isa_core::EncodeError;\n\n");

    // Top-level dispatch
    out.push_str(
        "pub fn encode(insn: &Instruction, out: &mut [u8]) -> Result<usize, EncodeError> {\n",
    );
    out.push_str("    match insn {\n");
    for f in &spec.formats {
        let variant = pascal(&f.name);
        let fields = encodable_fields(f);
        let pat: String = fields
            .iter()
            .map(|fld| fld.name.clone())
            .collect::<Vec<_>>()
            .join(", ");
        let args: String = fields
            .iter()
            .map(|fld| format!("*{}", fld.name))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            out,
            "        Instruction::{variant} {{ {pat} }} => encode_{}({args}, out),",
            f.name
        );
    }
    out.push_str("    }\n");
    out.push_str("}\n\n");

    // Per-format encoders
    for f in &spec.formats {
        emit_format_encoder(&mut out, f, spec);
    }
    out
}

